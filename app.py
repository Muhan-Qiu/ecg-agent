@st.cache_data(show_spinner=False)
def analyze(record):
    d = T.ecg_load(record)
    clean = T.preprocess(d["signal"], d["fs"])
    rpeaks = T.detect_beats(clean, d["fs"])
    res = {
        "fs": d["fs"], "leads": d["leads"], "duration_min": d["duration_min"],
        "n_samples": d["n_samples"],
        "quality": T.quality_check(d["signal"], d["fs"]),
        "measures": {**T.basic_measures(rpeaks, d["fs"]),
                     **T.rhythm_summary(rpeaks, d["fs"]),
                     **T.hrv_metrics(rpeaks, d["fs"])},
        "classification": T.classify_beats(record),
        "n_peaks": int(len(rpeaks)),
    }
    return res, d["signal"], clean, rpeaks


def wave_figure(signal, clean, rpeaks, fs, L, seconds=8):
    font = T._pick_cjk_font()
    if font:
        plt.rcParams["font.sans-serif"] = [font]
    plt.rcParams["axes.unicode_minus"] = False

    n = int(seconds * fs)
    t = np.arange(n) / fs
    pk = rpeaks[rpeaks < n]

    fig, ax = plt.subplots(figsize=(9, 3.0))
    ax.plot(t, signal[:n, 0], color="0.8", lw=0.8, label=L["raw"])
    ax.plot(t, clean[:n], color="#c0392b", lw=1.1, label=L["clean"])
    ax.plot(pk / fs, clean[pk], "o", mfc="none", mec="#123a5e", ms=8,
            label=L["peaks"])
    ax.set_xlabel(L["t_axis"], fontsize=9)
    ax.set_ylabel(L["amp_axis"], fontsize=9)
    ax.tick_params(labelsize=8)
    ax.legend(loc="upper right", fontsize=8, ncol=3, framealpha=.9)
    ax.grid(alpha=.25)
    fig.tight_layout()
    return fig


def pie_figure(counts, L):
    font = T._pick_cjk_font()
    if font:
        plt.rcParams["font.sans-serif"] = [font]
    plt.rcParams["axes.unicode_minus"] = False

    keys = [k for k in ("N", "S", "V", "F") if counts.get(k, 0) > 0]
    vals = [counts[k] for k in keys]
    colors = {"N": "#2e9e8f", "S": "#e8a33d", "V": "#c0392b", "F": "#8e6fb0"}

    fig, ax = plt.subplots(figsize=(4, 3.0))
    _, _, autot = ax.pie(
        vals, labels=[f"{L['cls'][k]}\n{counts[k]}" for k in keys],
        colors=[colors[k] for k in keys],
        autopct=lambda p: f"{p:.1f}%", startangle=90,
        textprops={"fontsize": 8},
        wedgeprops={"width": .42, "edgecolor": "white", "linewidth": 1.6})
    for a in autot:
        a.set_fontsize(7.5)
    ax.set_title(L["pie_title"], fontsize=10)
    fig.tight_layout()
    return fig


def build_report(record, res, messages, L):
    """把当前分析结果和对话整理成一份 Markdown 报告。"""
    m, c = res["measures"], res["classification"]
    lines = [
        f"# {L['report_title']}",
        "",
        f"- Record: `{record}`　|　Duration: {res['duration_min']} min"
        f"　|　Leads: {', '.join(res['leads'])}　|　fs: {res['fs']:.0f} Hz",
        f"- Signal quality: {'OK' if res['quality']['ok'] else 'BAD'}"
        f"　|　R peaks: {res['n_peaks']}",
        f"- *{L['report_gen']}*",
        "",
        "## Measurements / 测量",
        "",
        "| Field | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in m.items()]
    lines += ["", "## Beat classification / 逐搏分类", "",
              "| Class | Count |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in c["counts"].items()]
    lines += [f"| Abnormal (%) | {c['abnormal_pct']} |", ""]

    if messages:
        lines += ["## " + L["report_conv"], ""]
        for msg in messages:
            who = "**User:**" if msg["role"] == "user" else "**Agent:**"
            lines += [f"{who} {msg['content']}", ""]

    lines += ["---", f"*{L['disclaimer']}*", ""]
    return "\n".join(lines)


